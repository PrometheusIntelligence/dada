#!/usr/bin/env node
// lessons_index.mjs -- one index of every lesson GDADA has learned, built from the ledgers themselves.
//
//   node scripts/lessons_index.mjs [references-dir]          writes <references-dir>/lessons-index.md and prints the counts
//   node scripts/lessons_index.mjs [references-dir] --check  exits 1 if lessons-index.md is out of date (for CI / a stop test)
//
// It reads each ledger in its own format:
//   ### L<n> (date, game)[: title]  + **Rule:** ...   world-lessons, sprite-lessons, colossus-lessons
//   - H<n>. **title** ...                             holyc-lessons
//   - M<n>. **title** ...                             music-craft
//   - **E<n>. title** ...                             portrait-craft
//   ## P<n>. title  /  ### P<n>. title                map-craft
//   - R<n>. **title** ...                             production-lessons
// A ledger entry with no title is listed by the first sentence of its Rule.  Every id is prefixed by its ledger
// (world L5, sprite L5, ...) because the ledgers number independently.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const DIR = process.argv[2] && !process.argv[2].startsWith("--") ? process.argv[2] : join(dirname(fileURLToPath(import.meta.url)), "..", "references");
const check = process.argv.includes("--check");
const firstSentence = (s) => (s.replace(/\s+/g, " ").trim().match(/^.*?[.!?](?=\s|$)/) || [s.trim()])[0].replace(/\*\*/g, "");
const clip = (s, n = 170) => (s.length > n ? s.slice(0, n - 1).replace(/\s+\S*$/, "") + " ..." : s);

const LEDGERS = [
  { file: "world-lessons.md", name: "World (Place runs: maps, regions, systems, sources)", prefix: "world", kind: "L" },
  { file: "holyc-lessons.md", name: "HolyC and TempleOS (compiling, testing, shipping)", prefix: "holyc", kind: "H" },
  { file: "map-craft.md", name: "Map placement", prefix: "map", kind: "P" },
  { file: "sprite-lessons.md", name: "Sprites (Art runs)", prefix: "sprite", kind: "L" },
  { file: "portrait-craft.md", name: "Portraits and eyes", prefix: "portrait", kind: "E" },
  { file: "colossus-lessons.md", name: "Colossi (very large figures)", prefix: "colossus", kind: "L" },
  { file: "music-craft.md", name: "Music (one-voice 8-bit)", prefix: "music", kind: "M" },
  { file: "production-lessons.md", name: "Production (helpers, processes, repos, restarts)", prefix: "production", kind: "R" },
];

function parse(text, kind) {
  const out = [];
  if (kind === "L") {
    const parts = text.split(/^### (?=L\d+)/m).slice(1);
    for (const p of parts) {
      const head = p.split("\n")[0];
      const id = head.match(/^L(\d+)/)[1];
      const title = (head.match(/\):\s*(.+)$/) || [])[1];
      const rule = (p.match(/\*\*Rule:\*\*\s*([\s\S]*?)(?:\n\*\*|\n###|$)/) || [])[1] || "";
      const meta = (head.match(/\(([^)]*)\)/) || [])[1] || "";
      out.push({ id: `L${id}`, text: title ? title.replace(/\*\*/g, "") : firstSentence(rule), rule: firstSentence(rule), meta });
    }
  } else if (kind === "P") {
    for (const m of text.matchAll(/^#{2,3} P(\d+)\.\s*(.+)$/gm)) out.push({ id: `P${m[1]}`, text: m[2].trim() });
  } else if (kind === "E") {
    for (const m of text.matchAll(/^- \*\*E(\d+)\.\s*(.+?)\*\*/gm)) out.push({ id: `E${m[1]}`, text: m[2].trim() });
  } else {
    for (const m of text.matchAll(new RegExp(`^- ${kind}(\\d+)\\.\\s*\\*\\*(.+?)\\*\\*`, "gm"))) out.push({ id: `${kind}${m[1]}`, text: m[2].trim() });
  }
  return out;
}

const lines = ["# Lessons index (every ledger, one page)", "",
  "Generated by `scripts/lessons_index.mjs` from the ledgers themselves; do not edit by hand (rerun it after appending a lesson).",
  "Read this page first in any run, then read in full the ledger for the kind of work you are doing. Ids are per ledger: cite",
  "them as `world L26`, `holyc H22`, `map P14`.", ""];
const counts = [];
for (const L of LEDGERS) {
  const p = join(DIR, L.file);
  if (!existsSync(p)) continue;
  const items = parse(readFileSync(p, "utf8"), L.kind);
  counts.push(`${L.prefix} ${items.length}`);
  lines.push(`## ${L.name} -- [${L.file}](${L.file}) (${items.length})`, "", "| id | lesson | rule (first sentence) |", "|---|---|---|");
  for (const it of items) {
    const rule = it.rule && it.rule !== it.text ? clip(it.rule) : "";
    lines.push(`| ${L.prefix} ${it.id} | ${clip(it.text, 140).replace(/\|/g, "/")} | ${rule.replace(/\|/g, "/")} |`);
  }
  lines.push("");
}
const total = counts.reduce((s, c) => s + Number(c.split(" ")[1]), 0);
lines.splice(5, 0, `${total} lessons: ${counts.join(", ")}.`, "");
const outText = lines.join("\n") + "\n";
const target = join(DIR, "lessons-index.md");
if (check) {
  const same = existsSync(target) && readFileSync(target, "utf8") === outText;
  console.log(same ? "lessons_index: up to date" : "lessons_index: OUT OF DATE (run node scripts/lessons_index.mjs)");
  process.exit(same ? 0 : 1);
}
writeFileSync(target, outText);
console.log(`lessons_index: ${total} lessons (${counts.join(", ")}) -> ${target}`);
