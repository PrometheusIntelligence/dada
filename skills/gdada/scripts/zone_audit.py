"""zone_audit.py -- how the player gets between the world's zones (regions): every door that crosses a region boundary, what gates it, and
whether each zone has the "playground" property the person asked for (2026-11-10: "multiple ways to get to new zones, playground style").

For every region: its entrances (doors from other regions into it), how many distinct regions they come from, and the kinds of gate on them:
  open      no condition
  time      hours=
  know      needs=answered:N / asked:N (the notebook)
  item      lock=IT_X
  flag      flag=FL_X (set by a standoff, a line, a deed) or a variant that hides the door (unless=)
A zone passes when it has at least 2 entrances from at least 2 different regions, and, if every entrance is gated, at least 2 different KINDS
of gate (so a player who cannot or will not do one thing has another road).  Transitions made in code (the bed's descent, an encounter's
win that moves you) are not doors and are not counted.  It also reports depth: the fewest region-crossings from the start (room) ignoring gates,
and which zones are dead ends (one way in, one way out, same door).  Writes design/ZONE-AUDIT.md.  usage: python3 tools/zone_audit.py"""
import os, re, glob, collections

import sys
# gdada copy: the game directory is the first argument (default: the current directory). The game must use the world text
# format of The Holy Temple (world/**/*.map with `map`, `region`, `door X Y -> MAP X Y face [gates]` lines; cast/**/*.json).
R = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.getcwd()
os.makedirs(os.path.join(R, "design"), exist_ok=True)
maps = {}
for f in glob.glob(os.path.join(R, "world", "**", "*.map"), recursive=True):
    t = open(f, encoding="utf-8").read()
    m = re.search(r"^map (\w+)", t, re.M)
    if not m: continue
    reg = re.search(r"^region (\w+)", t, re.M)
    maps[m[1]] = dict(region=reg[1] if reg else "misc", text=t)

def kinds(rest):
    k = []
    if "hours=" in rest: k.append("time")
    if re.search(r"needs=(answered|asked):", rest): k.append("know")
    if "lock=IT_" in rest: k.append("item")
    if "flag=FL_" in rest: k.append("flag")
    return k or ["open"]

edges = []   # (from_map, from_region, to_map, to_region, kinds)
hidden = collections.defaultdict(set)
for name, m in maps.items():
    for v in re.finditer(r"^variant .*unless=(\S+)(?:.*\n)((?:\s+patch.*\n)*)", m["text"], re.M):
        for p in re.finditer(r"patch (\d+) (\d+) = (.)", v[2]): hidden[name].add((int(p[1]), int(p[2])))
    for d in re.finditer(r"^door (\d+) (\d+) -> (\w+) \d+ \d+ \w+(.*)$", m["text"], re.M):
        to = d[3]
        if to not in maps: continue
        k = kinds(d[4])
        if (int(d[1]), int(d[2])) in hidden[name] and "flag" not in k: k = [x for x in k if x != "open"] + ["flag"]
        edges.append((name, m["region"], to, maps[to]["region"], k))

regions = sorted({m["region"] for m in maps.values()})
cross = [e for e in edges if e[1] != e[3]]
inn = collections.defaultdict(list); out = collections.defaultdict(list)
for e in cross: inn[e[3]].append(e); out[e[1]].append(e)

# depth from the start, ignoring gates (fewest region crossings)
start = maps.get("room", {}).get("region", "home")
depth = {start: 0}; q = collections.deque([start])
while q:
    r = q.popleft()
    for e in out[r]:
        if e[3] not in depth: depth[e[3]] = depth[r] + 1; q.append(e[3])

rows, fails = [], 0
for r in regions:
    ins = inn[r]
    srcs = sorted({e[1] for e in ins}); ks = sorted({k for e in ins for k in e[4]})
    gated_only = "open" not in ks
    ok = len(ins) >= 2 and len(srcs) >= 2 and (not gated_only or len(ks) >= 2)
    if r == start: ok = True
    fails += not ok
    rows.append((r, len(ins), srcs, ks, depth.get(r, "-"), ok))

o = ["# Zone audit", "", "Generated by `tools/zone_audit.py`. A zone passes the playground test with 2+ entrances from 2+ different regions (and 2+ kinds of",
     "gate if none is open: time, know, item, flag). Depth: fewest region-crossings from your room, ignoring gates.", "",
     "| zone | entrances | from | kinds of way in | depth | playground |", "|---|---|---|---|---|---|"]
for r, n, srcs, ks, dp, ok in sorted(rows, key=lambda x: (x[5], x[0])):
    o.append(f"| {r} | {n} | {', '.join(srcs)} | {', '.join(ks)} | {dp} | {'yes' if ok else '**no**'} |")
o += ["", "## Every crossing", "", "| from | to | gate |", "|---|---|---|"]
for e in sorted(cross, key=lambda e: (e[3], e[1], e[0])):
    o.append(f"| {e[1]}/{e[0]} | {e[3]}/{e[2]} | {', '.join(e[4])} |")
open(os.path.join(R, "design", "ZONE-AUDIT.md"), "w").write("\n".join(o) + "\n")
print(f"zone_audit: {len(regions)} zones, {len(cross)} crossings, {fails} fail the playground test")
for r, n, srcs, ks, dp, ok in sorted(rows, key=lambda x: (x[5], x[0])):
    print(f"  {'ok ' if ok else 'NO '} {r:11s} in={n:2d} from={','.join(srcs):40s} kinds={','.join(ks):20s} depth={dp}")
